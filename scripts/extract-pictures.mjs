// Copies the few Fluent Emoji Flat pictures (MIT, Microsoft) that Okienko uses
// into src/assets/pictures.ts, so the app ships only what it needs.
// Run: node scripts/extract-pictures.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/fluent-emoji-flat/icons.json'), 'utf8'))

const pictures = {
  kot: 'cat-face',
  pies: 'dog-face',
  slonce: 'sun',
  gwiazda: 'star',
  jablko: 'red-apple',
  rybka: 'tropical-fish',
  kwiatek: 'blossom',
  rakieta: 'rocket',
  tecza: 'rainbow',
  balon: 'balloon',
  notes: 'memo',
  choinka: 'evergreen-tree',
  drzewo: 'deciduous-tree',
}

const out = {}
for (const [id, name] of Object.entries(pictures)) {
  const icon = set.icons[name]
  if (!icon) throw new Error(`Missing ${name}`)
  out[id] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${icon.width ?? set.width} ${icon.height ?? set.height}">${icon.body}</svg>`
}

const src = `// Generated by scripts/extract-pictures.mjs. Do not edit by hand.
// Fluent Emoji Flat, (c) Microsoft Corporation, MIT licence.
export const pictureSvg = ${JSON.stringify(out, null, 2)} as const

export type PictureId = keyof typeof pictureSvg
`
writeFileSync(new URL('../src/assets/pictures.ts', import.meta.url), src)
console.log('Wrote', Object.keys(out).length, 'pictures')
